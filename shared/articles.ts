許多人以為「繼承」就是繼承財產，但實際上，繼承是全面的——你不只繼承了被繼承人的財產，也繼承了他的**債務**。如果父母生前欠了一大筆錢，子女繼承後可能面臨被債主追討的困境。

幸好，台灣民法提供了兩種保護機制：**拋棄繼承**和**限定繼承**。

